#!/usr/bin/env python3
"""
score_results.py  --  computes every reported value and writes LaTeX rows/tables ready to paste.

Inputs (all optional; missing inputs leave the related cells as n/a):
  results/runs.jsonl            from run_experiments.py            -> Tables 2, 5
  sheets/drug_names.csv         filled by a human                      -> Table 2 (Arabic name accuracy)
  sheets/error_audit.csv        filled by a human                      -> Table 3 (recall)
  sheets/flag_audit.csv         filled by a human                      -> Table 3 (TP, FP, precision)
  results/ocr_confidence.csv  OCR study (6 near-duplicates excluded) -> Table 4, Table 5 OCR row

Output: results/paper_tables.tex  and a plain-text summary on screen.
"""
import argparse
import csv
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent


def read_csv(p):
    p = Path(p)
    if not p.exists():
        return []
    with p.open(encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def col(row, prefix):
    """Return the value of the first column whose header starts with prefix (headers carry hints)."""
    for k, v in row.items():
        if k and k.strip().lower().startswith(prefix):
            return (v or "").strip().lower()
    return ""


def pct(a, b):
    return f"{100 * a / b:.1f}\\%" if b else "n/a"


def mean_sd(xs, nd=1):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "n/a"
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f}"
    return f"{st.mean(xs):.{nd}f} $\\pm$ {st.stdev(xs):.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(KIT / "results" / "runs.jsonl"))
    ap.add_argument("--sheets", default=str(KIT / "sheets"))
    ap.add_argument("--ocr", default=str(KIT / "results" / "ocr_confidence.csv"))
    ap.add_argument("--ocr-dups", default=str(KIT / "results" / "ocr_duplicates.txt"))
    ap.add_argument("--tau", type=float, default=0.60, help="OCR threshold on the paper's 0-1 scale")
    ap.add_argument("--level", default="grade8", help="reading level used for Tables 2-3")
    ap.add_argument("--out", default=str(KIT / "results" / "paper_tables.tex"))
    args = ap.parse_args()

    runs = []
    if Path(args.runs).exists():
        runs = [json.loads(l) for l in Path(args.runs).read_text(encoding="utf-8").splitlines() if l.strip()]
    ok = [r for r in runs if "error" not in r]
    models = sorted({r["model"] for r in runs}, key=lambda m: float(m.split(":")[-1].rstrip("b")) if m.split(":")[-1].rstrip("b").replace(".", "").isdigit() else 0)
    tex = ["% Generated by score_results.py -- paste into the paper. Cells marked n/a need more data.\n"]
    summary = []

    # ---------------- Table 2: bilingual model comparison ----------------
    drugs = read_csv(Path(args.sheets) / "drug_names.csv")
    t2 = []
    for m in models:
        g = [r for r in ok if r["model"] == m and r["level"] == args.level]
        en = [r for r in g if r["lang"] == "en"]; ar = [r for r in g if r["lang"] == "ar"]
        judged = [d for d in drugs if d.get("model") == m and col(d, "judgement")]
        correct = sum(col(d, "judgement") == "correct" for d in judged)
        name_acc = f"{correct}/{len(judged)} ({pct(correct, len(judged))})" if judged else "n/a"
        fe = f"EN {pct(sum(r['facts_kept'] for r in en), sum(r['facts_total'] for r in en))}" if en else "EN n/a"
        fa = f"AR {pct(sum(r['facts_kept'] for r in ar), sum(r['facts_total'] for r in ar))}" if ar else "AR n/a"
        lat = mean_sd([r["sec_total"] for r in g])
        vram = max([r["mem_vram_gb"] or 0 for r in g], default=0)
        tot = max([r["mem_total_gb"] or 0 for r in g], default=0)
        mem = f"{vram:.1f} ({tot:.1f})" if tot else "n/a"
        t2.append(f"    Qwen2.5 {m.split(':')[-1].upper()} & {name_acc} & {fe} / {fa} & {lat} & {mem} \\\\")
        summary.append(f"[T2] {m}: names {name_acc}; facts {fe} / {fa}; latency {lat} s; memory VRAM(total) {mem} GB")
    if t2:
        tex += ["% ---- Table 2 rows (Model & Arabic name accuracy & Clinical facts kept & Latency (s) & Memory (GB)) ----",
                f"% level={args.level}; facts: EN all facts, AR digit-bearing facts; latency = simplify+verify, mean $\\pm$ SD over runs;",
                "% memory = VRAM (total) reported by Ollama /api/ps.", *t2, ""]

    # ---------------- Table 3: verified-error detection ----------------
    errs = read_csv(Path(args.sheets) / "error_audit.csv")
    flags = read_csv(Path(args.sheets) / "flag_audit.csv")
    E = {e["error_id"] for e in errs if col(e, "occurred") == "yes"}
    judged_flags = [f for f in flags if col(f, "real_error") in ("yes", "no")]
    if E or judged_flags:
        rows3 = []
        def layer_stats(layers):
            fl = [f for f in judged_flags if f["layer"] in layers]
            tp = sum(col(f, "real_error") == "yes" for f in fl)
            fp = sum(col(f, "real_error") == "no" for f in fl)
            detected = {col(f, "error_id").strip() for f in fl if col(f, "real_error") == "yes"}
            detected = {d for d in detected if d} & {e.lower() for e in E}
            prec = f"{tp / (tp + fp):.2f}" if tp + fp else "n/a"
            rec = f"{len(detected) / len(E):.2f}" if E else "n/a"
            return tp, fp, prec, rec, len(detected)
        for name, layers in (("Numerical only", {"L1"}), ("Semantic only", {"L2"}), ("Combined", {"L1", "L2"}), ("Script check (L0)", {"L0"})):
            tp, fp, prec, rec, nd = layer_stats(layers)
            rows3.append(f"    {name} & {tp} & {fp} & {prec} & {rec} \\\\")
            summary.append(f"[T3] {name}: TP {tp}, FP {fp}, precision {prec}, recall {rec} ({nd}/{len(E)} confirmed errors detected)")
        tex += ["% ---- Table 3 rows (Checker & TP & FP & Precision & Recall) ----",
                f"% {len(E)} confirmed errors in the audited outputs; recall = confirmed errors flagged / all confirmed errors.",
                "% Precision 'n/a' = the checker raised no flags. Combined = union of numerical and semantic flags.",
                *rows3, ""]

    # ---------------- Table 4 + OCR sweep ----------------
    ocr = read_csv(args.ocr)
    if ocr:
        dups = set(Path(args.ocr_dups).read_text().split()) if Path(args.ocr_dups).exists() else set()
        groups = {"Clean print": "printed", "Degraded print": "printed_scan", "Handwriting": "handwritten"}
        def confs(g):
            return [int(r["confidence"]) for r in ocr if r["group"] == g and r["confidence"].isdigit()
                    and not (g == "handwritten" and r["file"] in dups)]
        thr = round(args.tau * 100)
        t4 = []
        for label, g in groups.items():
            c = confs(g); acc = sum(x >= thr for x in c)
            should_accept = g != "handwritten"
            wa = 0 if should_accept else acc
            wr = (len(c) - acc) if should_accept else 0
            t4.append(f"    {label} & {len(c)} & {acc} & {wa} & {wr} \\\\")
            summary.append(f"[T4] tau={args.tau:.2f} {label}: n={len(c)} accepted={acc} wrongly_accepted={wa} wrongly_refused={wr}")
        tex += [f"% ---- Table 4 rows (Input type & Documents & Accepted & Wrongly accepted & Wrongly refused), tau = {args.tau:.2f} ----",
                "% Reference labels: printed documents should be accepted; handwritten prescriptions should be refused.",
                *t4, ""]
        hw = confs("handwritten"); pr = confs("printed") + confs("printed_scan")
        sweep = []
        for t in (0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85):
            T = round(t * 100)
            sweep.append(f"{t:.2f}: HW refused {100*sum(x < T for x in hw)/len(hw):.1f}\\%, print accepted {sum(x >= T for x in pr)}/{len(pr)}")
        ocr_row = ("$\\tau$ = 0.60--0.80 accepts all " + str(len(pr)) + " printed controls and refuses "
                   f"{100*sum(x < 60 for x in hw)/len(hw):.1f}--{100*sum(x < 80 for x in hw)/len(hw):.1f}\\% of {len(hw)} handwritten images")
        tex += ["% ---- OCR threshold sweep (for Table 5 'OCR threshold sweep' row) ----", *[f"%   {s}" for s in sweep],
                f"% Suggested Table 5 cell: {ocr_row}", ""]
        summary.append(f"[T5-OCR] {ocr_row}")

    # ---------------- Table 5: ablations ----------------
    if ok:
        big = models[-1]
        lv = []
        for level in ("grade6", "grade8", "adult"):
            en = [r for r in ok if r["model"] == big and r["lang"] == "en" and r["level"] == level]
            if en:
                lv.append(f"{level.replace('grade','G')}: FKGL {mean_sd([r['fkgl_out'] for r in en])}, facts {pct(sum(r['facts_kept'] for r in en), sum(r['facts_total'] for r in en))}")
        tex.append(f"% Table 5 / Target grade ({big}, EN): " + "; ".join(lv))
        summary.append(f"[T5-grade] {big} EN: " + "; ".join(lv))
        mm = []
        for m in models:
            en = [r for r in ok if r["model"] == m and r["lang"] == "en" and r["level"] == args.level]
            ar = [r for r in ok if r["model"] == m and r["lang"] == "ar" and r["level"] == args.level]
            mm.append(f"{m}: EN {pct(sum(r['facts_kept'] for r in en), sum(r['facts_total'] for r in en))}, AR {pct(sum(r['facts_kept'] for r in ar), sum(r['facts_total'] for r in ar))}")
        tex.append("% Table 5 / Model size (facts kept, " + args.level + "): " + "; ".join(mm))
        summary.append("[T5-model] " + "; ".join(mm))
        # repeated runs: per-run retention for the big model, failure rates
        per_run = defaultdict(lambda: [0, 0])
        for r in ok:
            if r["model"] == big and r["level"] == args.level:
                per_run[(r["lang"], r["run"])][0] += r["facts_kept"]; per_run[(r["lang"], r["run"])][1] += r["facts_total"]
        rr = []
        for lang in ("en", "ar"):
            vals = [100 * k / t for (l, _), (k, t) in per_run.items() if l == lang and t]
            if vals:
                rr.append(f"{lang.upper()} facts {mean_sd(vals)}\\% over {len(vals)} runs")
        allr = [r for r in runs if r["model"] == big and r["level"] == args.level]
        api_fail = sum("error" in r for r in allr)
        script_fail = sum(r.get("flags_L0", 0) > 0 for r in allr if r.get("lang") == "ar")
        n_ar = sum(r.get("lang") == "ar" for r in allr)
        rr.append(f"API failures {api_fail}/{len(allr)}; Arabic outputs with wrong-script flags {script_fail}/{n_ar}")
        tex.append(f"% Table 5 / Multiple runs ({big}, {args.level}): " + "; ".join(rr))
        summary.append("[T5-runs] " + "; ".join(rr))

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(summary) if summary else "No inputs found.")
    print(f"\nLaTeX written to {args.out}\n")


if __name__ == "__main__":
    main()
